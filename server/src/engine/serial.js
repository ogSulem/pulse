/** План сезона: названия, логлайны, крючки и график выхода. */
export function planSeason({ series, startAt = null, perWeek = 2 } = {}) {
  const bible = typeof series.bible === 'string' ? JSON.parse(series.bible || '{}') : (series.bible || {});
  const g = GENRE(series.genre);
  const rnd = seededRandom(`season-${series.id || series.title}`);

  const count = clamp(num(series.episodes_planned, 6), 3, 8);
  const steps = ARC_STEPS.slice(0, count);
  const start = startAt ? new Date(startAt) : new Date();

  const episodes = steps.map((step, i) => {
    const place = pick(g.locations, rnd);
    const artifact = pick(g.artifacts, rnd);
    const threat = pick(g.threats, rnd);
    const title = `${step.title}`;
    const dayOffset = Math.floor(i / perWeek) * 7 + (i % perWeek) * 3;
    const publishAt = new Date(start.getTime() + dayOffset * 86400000).toISOString();
    return {
      number: i + 1,
      title,
      arc: step.key,
      logline: `${bible.characters?.[0]?.name || 'Герой'} идёт ${locPrep(place)} ${inflect(place, 'acc')} за ${inflect(artifact, 'ins')}. Правила в этот раз меняет ${threat}.`,
      hook: `Вопрос серии: ${step.turn}?`,
      cliffhanger: step.end,
      newElement: `${artifact} · ${place}`,
      publishAt,
      minutes: Math.round(num(series.episode_sec, 900) / 60),
    };
  });

  return {
    season: num(series.season, 1),
    count,
    cadence: perWeek >= 2 ? '2 серии в неделю, первые две — вместе' : '1 серия в неделю',
    episodes,
    advice: [
      'Первые 2–3 серии выкладываем вместе: новому зрителю нужен запас для запойного просмотра.',
      'Дальше — ровный ритм. YouTube Shows и плейлист «по порядку» включают автоплей следующей серии.',
      'Крючок в конце каждой серии сильнее, чем хук в начале: он возвращает зрителя через неделю.',
    ],
  };
}

