/** Числительные: 1 секунда / 3 секунды / 6 секунд. */
function plural(n, forms) {
  const abs = Math.abs(Math.round(num(n, 0))) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return forms[2];
  if (last === 1) return forms[0];
  if (last >= 2 && last <= 4) return forms[1];
  return forms[2];
}

/** Род по имени: нужен для глаголов прошедшего времени («оказался/оказалась»). */
function guessGender(name) {
  const low = String(name || '').toLowerCase();
  if (FEMALE_NAMES.has(low)) return 'f';
  if (MALE_NAMES.has(low)) return 'm';
  if (/(а|я)$/.test(low)) return 'f';
  if (/(й|ь)$/.test(low)) return 'm';
  if (/[бвгджзклмнпрстфхцчшщ]$/.test(low)) return 'm';
  return 'f';
}

const stripPunct = (w) => String(w).replace(/[«»"'.,:;!?()]/g, '');
const isCapital = (w) => Boolean(w) && w[0] === w[0].toUpperCase() && w[0] !== w[0].toLowerCase();

function adjForm(word, form) {
  if (!word || form === 'nom') return word;
  const low = word.toLowerCase();
  const table = ADJ_CASE[low.slice(-2)];
  if (!table) return word;
  const suffix = form === 'genPl' ? table.genPl : table[form];
  if (!suffix) return word;
  const out = low.slice(0, -2) + suffix;
  return isCapital(word) ? out[0].toUpperCase() + out.slice(1) : out;
}

function nounGender(word, hint) {
  const bare = stripPunct(word).toLowerCase();
  if (!bare) return hint || 'm';
  if (INDECLINABLE.has(bare)) return 'indecl';
  if (MASCULINE_SOFT.has(bare)) return 'm';
  if (/[ая]$/.test(bare)) return 'f';
  if (/ь$/.test(bare)) return 'f';
  if (/й$/.test(bare)) return 'm';
  if (/[ое]$/.test(bare)) return 'n';
  if (/[бвгджзклмнпрстфхцчшщ]$/.test(bare)) return 'm';
  return hint || 'indecl';
}

function nounForm(word, form, hint) {
  if (!word || form === 'nom') return word;
  const lead = (word.match(/^[«"(]+/) || [''])[0];
  const tail = (word.match(/[.,:;!?»")]+$/) || [''])[0];
  const core = word.slice(lead.length, word.length - tail.length);
  const gender = nounGender(core, hint);
  if (!core || gender === 'indecl') return word;
  const low = core.toLowerCase();
  const last = low.slice(-1);
  const stem = low.slice(0, -1);
  let out = low;

  if (gender === 'm') {
    if (last === 'й') {
      out = form === 'gen' || form === 'acc' ? `${stem}я`
        : form === 'dat' ? `${stem}ю` : form === 'ins' ? `${stem}ем` : `${stem}е`;
    } else if (last === 'ь') {
      out = form === 'acc' ? low
        : form === 'gen' ? `${stem}я`
          : form === 'dat' ? `${stem}ю` : form === 'ins' ? `${stem}ем` : `${stem}е`;
    } else {
      // «образец» → «образцом»: беглая гласная в конце основы
      const base = /ец$/.test(low) && form === 'ins' ? low.slice(0, -2) + 'ц' : low;
      out = form === 'gen' ? `${low}а`
        : form === 'acc' ? low
          : form === 'dat' ? `${low}у`
            : form === 'ins' ? `${base}ом` : `${low}е`;
    }
  } else if (gender === 'f') {
    if (last === 'а') {
      const s = low.slice(0, -1);
      const hush = /[гкхжшщчц]$/.test(s);
      const sibilant = /[жшщчц]$/.test(s);
      out = form === 'acc' ? `${s}у`
        : form === 'gen' ? `${s}${hush ? 'и' : 'ы'}`
          : form === 'dat' ? `${s}е`
            : form === 'ins' ? `${s}${sibilant ? 'ей' : 'ой'}` : `${s}е`;
    } else if (last === 'я') {
      const s = low.slice(0, -1);
      const ia = /и$/.test(s);
      out = form === 'acc' ? `${s}ю`
        : form === 'gen' ? `${s}и`
          : form === 'ins' ? `${s}ей`
            : form === 'dat' || form === 'prep' ? `${s}${ia ? 'и' : 'е'}` : `${s}и`;
    } else if (last === 'ь') {
      out = form === 'acc' ? low
        : form === 'ins' ? `${stem}ью` : `${stem}и`;
    }
  } else if (gender === 'n') {
    out = last === 'о'
      ? form === 'gen' ? `${low}а`
        : form === 'dat' ? `${low}у`
          : form === 'ins' ? `${low}ом`
            : form === 'acc' ? low : `${low}е`
      : form === 'gen' ? `${low}я`
        : form === 'dat' ? `${low}ю`
          : form === 'ins' ? `${low}ем`
            : form === 'acc' ? low : `${low}е`;
  }

  return lead + (isCapital(core) ? out[0].toUpperCase() + out.slice(1) : out) + tail;
}

/**
 * Склоняет словосочетание целиком: «придорожный мотель» → «в придорожном мотеле».
 * form: nom | acc | gen | dat | ins | prep
 */
function inflect(phrase, form = 'nom') {
  const src = String(phrase || '').trim();
  if (!src || form === 'nom') return src;
  const parts = src.split(/(\s+)/);
  let idx = -1;
  for (let i = 0; i < parts.length; i += 2) {
    const w = parts[i];
    if (!w) continue;
    if (/^[«"(]/.test(w)) break;
    if (PREPOSITIONS.has(w.toLowerCase())) continue;
    idx = i;
    break;
  }
  if (idx < 0) return src;

  const first = parts[idx];
  const kind = ADJ_KIND[first.toLowerCase().slice(-2)];
  if (!kind) {
    parts[idx] = nounForm(first, form);
    return parts.join('');
  }

  parts[idx] = adjForm(first, form === 'gen' && kind === 'pl' ? 'genPl' : form);
  for (let i = idx + 2; i < parts.length; i += 2) {
    const w = parts[i];
    if (!w) continue;
    if (/^[«"(]/.test(w) || PREPOSITIONS.has(w.toLowerCase())) break;
    const k = ADJ_KIND[w.toLowerCase().slice(-2)];
    if (k) { parts[i] = adjForm(w, form === 'gen' && k === 'pl' ? 'genPl' : form); continue; }
    parts[i] = nounForm(w, form, kind === 'pl' ? null : kind);
    break;
  }
  return parts.join('');
}

/** Падежи для имён собственных: у Тимура, к Вере, с Ольгой. */
function nameForm(name, form = 'gen') {
  const src = String(name || '').trim();
  if (!src || form === 'nom') return src;
  const low = src.toLowerCase();
  const female = /[ая]$/.test(low) && !MALE_NAMES.has(low);
  let out = src;
  if (female) {
    const s = src.slice(0, -1);
    out = form === 'acc' ? `${s}у`
      : form === 'ins' ? `${s}ой`
        : form === 'dat' ? `${s}е`
          : form === 'prep' ? `${s}е` : `${s}${/[гкхжшщч]$/i.test(s) ? 'и' : 'ы'}`;
  } else if (/[йь]$/.test(low)) {
    const s = src.slice(0, -1);
    out = form === 'acc' || form === 'gen' ? `${s}я`
      : form === 'dat' ? `${s}ю` : `${s}ем`;
  } else if (/я$/.test(low)) {
    // Илья, Никита: мужское имя на -я склоняется как женское, но с другой основой
    const s = src.slice(0, -1);
    out = form === 'acc' ? `${s}ю` : form === 'gen' ? `${s}и`
      : form === 'dat' || form === 'prep' ? `${s}е` : `${s}ей`;
  } else {
    out = form === 'gen' || form === 'acc' ? `${src}а`
      : form === 'dat' ? `${src}у` : `${src}ом`;
  }
  return out;
}

// «на станции», «на складе» — предлог зависит от места, а не от падежа.
const NA_PLACES = /(станц|мельниц|площад|рек[аеу]|дорог|пол[ея]|крыш|окраин|берег|улиц|вокзал|чердак|мост|лестниц|башн|склад|этаж|перевал|побережь)/i;
function locPrep(place) {
  return NA_PLACES.test(String(place || '')) ? 'на' : 'в';
}

function capFirst(text) {
  const t = String(text || '').trim();
  if (!t) return t;
  if (!/[a-zа-яё]/i.test(t[0])) return t;    // «...», — (не трогаем)
  return t[0].toUpperCase() + t.slice(1);
}

/** Склейка реплик в текст сцены: каждое предложение с большой буквы. */
function sentenceJoin(parts) {
  return parts
    .map((p) => String(p || '').trim())
    .filter(Boolean)
    .map((p, i) => (i === 0 ? capFirst(p) : capFirst(p)))
    .join(' ')
    .replace(/\s+/g, ' ')
    .replace(/\s+([.,:;!?])/g, '$1')
    .trim();
}

